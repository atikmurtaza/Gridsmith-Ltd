-- K-08 — `press_path_results` and the ETH-04 audit column.
-- Source: `press/SCHEMA.md` §7 (table) and §8 (`v_path_finder_honesty`).
--
-- **Two constraints are here that §7 does not carry, and both exist for one reason:
-- non-negotiable #9 is audited from this table and nothing else.** `TECH-SPEC.md` §38 —
-- *"if `press_path_results` shows zero non-Gridsmith recommendations after a month of
-- traffic, the tool is broken"*. A column that records the honesty of a recommendation is
-- only evidence if it cannot disagree with the recommendation it describes.
--
--   * `outcome` is closed to the same six keys `pathOutcome.key` is closed to in
--     `sanity/schemas/pathFinderConfig.ts`, enforced by `check-schemas.mjs`'s `CLOSED_LISTS`.
--     `K-01`'s reason applied one layer down: a free-text `outcome` lets a write record a
--     seventh key that the honesty query then counts as neither honest nor Gridsmith.
--   * `press_path_honesty_agrees` derives the audit column from the outcome rather than
--     trusting the writer. `IMPLEMENTATION-PLAN.md` 3.7's acceptance is *"`is_gridsmith_outcome`
--     written correctly"*, and until now the only thing that could make it correct was
--     application discipline. `self-service` and `not-ready` are the two ETH-04 outcomes,
--     named as such in `TECH-SPEC.md` §38; the other four are Gridsmith services.
--
-- `lib/path/recommend.ts` returns `isGridsmithOutcome: null` for an outcome key that is not in
-- the config, deliberately, so that an unknown can never be recorded as a Gridsmith one. Both
-- `not null` and the check above turn that null into a rejected insert rather than a silent
-- `false`, which would count an unknown as an honest outcome and inflate the audit.
--
-- **RLS with no policy at all.** Results are written by the server. There is no anon
-- capability here: an INSERT policy would let any browser forge the ETH-04 audit trail, which
-- is the one record that can show the Path Finder has stopped recommending against Gridsmith.
-- `app/api/rls-drift/route.ts` asserts both halves against the live database as `anon`.

create table press_path_results (
  id                   text primary key,            -- nanoid(12), generated by the writer
  created_at           timestamptz not null default now(),
  session_id           text,
  config_version       int not null,
  answers              jsonb not null,
  outcome              text not null,
  is_gridsmith_outcome boolean not null,            -- the ETH-04 audit column
  completed            boolean not null default false,
  last_step            integer,
  lead_id              uuid references leads(id),
  expires_at           timestamptz not null default (now() + interval '90 days'),

  constraint press_path_outcome_known check (
    outcome in ('full-package', 'ghostwriting', 'assessment-first',
                'content-programme', 'self-service', 'not-ready')
  ),
  constraint press_path_honesty_agrees check (
    is_gridsmith_outcome = (outcome not in ('self-service', 'not-ready'))
  )
);

create index press_path_outcome_idx on press_path_results (outcome, created_at desc);
create index press_path_honest_idx  on press_path_results (is_gridsmith_outcome, created_at desc);

alter table press_path_results enable row level security;

-- The ETH-04 audit. `security_invoker` and the revoke are both required and either alone
-- leaves a hole — that is `0002`'s finding, and it is a Postgres default rather than a
-- one-off, so every view this repository creates carries both. `check:rls` enforces it.
create view v_path_finder_honesty as
select date_trunc('month', created_at) as month,
       count(*) filter (where completed)                              as completions,
       count(*) filter (where completed and not is_gridsmith_outcome) as honest_outcomes,
       round(100.0 * count(*) filter (where completed and not is_gridsmith_outcome)
             / nullif(count(*) filter (where completed), 0), 1)       as honest_pct
from press_path_results group by 1 order by 1 desc;

alter view v_path_finder_honesty set (security_invoker = true);
revoke all on v_path_finder_honesty from anon, authenticated;
